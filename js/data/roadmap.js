// dailyTime 프로필 값 → 루틴 키 매핑
export function routineFor(dailyTime) {
  if (!dailyTime) return DAILY_ROUTINES["60분"];
  if (dailyTime.startsWith("30")) return DAILY_ROUTINES["30분"];
  if (dailyTime.startsWith("90")) return DAILY_ROUTINES["90분"];
  if (dailyTime.startsWith("120")) return DAILY_ROUTINES["120분"];
  return DAILY_ROUTINES["60분"];
}

export function weekInfo(dayNum) {
  const week = Math.min(Math.ceil(dayNum / 7), 12);
  const phase = PROGRAM.phases[Math.min(Math.floor((week - 1) / 4), 2)];
  const weekData = phase.weeks.find((w) => w.week === week) || phase.weeks[phase.weeks.length - 1];
  return { week, phase, weekData };
}
